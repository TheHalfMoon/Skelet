"""AF-12 release SBOM conformance tests (offline).

Validates the committed sbom.json generated by scripts/generate_sbom.py:
CycloneDX envelope, sorted deterministic components, well-formed purls,
and consistency with the committed lockfile and requirements pins.
Never touches the network.
"""

from __future__ import annotations

import json
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SBOM_PATH = ROOT / "sbom.json"
LOCK_PATH = ROOT / "pnpm-lock.yaml"
REQUIREMENTS_PATH = ROOT / "requirements-ci.txt"

PURL_RE = re.compile(r"^pkg:(npm|pypi)/(@[^/]+/)?[^@/][^@]*@[^@\s]+$")
GIT_SHA_RE = re.compile(r"^[0-9a-f]{40}$")


def load_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


class SbomTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.bom = load_json(SBOM_PATH)

    def test_cyclonedx_envelope(self) -> None:
        self.assertEqual(self.bom["bomFormat"], "CycloneDX")
        self.assertEqual(self.bom["specVersion"], "1.5")
        self.assertEqual(self.bom["metadata"]["component"]["name"], "skelet")
        self.assertTrue(GIT_SHA_RE.match(self.bom["metadata"]["repoHead"]))

    def test_components_sorted_and_wellformed(self) -> None:
        components = self.bom["components"]
        self.assertGreater(len(components), 100)
        purls = [c["purl"] for c in components]
        self.assertEqual(sorted(purls), purls)
        self.assertEqual(len(set(purls)), len(purls))
        for component in components:
            with self.subTest(purl=component["purl"]):
                self.assertTrue(PURL_RE.match(component["purl"]))
                self.assertEqual(component["type"], "library")

    def test_pinned_toolchain_present(self) -> None:
        purls = {c["purl"] for c in self.bom["components"]}
        for expected in (
            "pkg:npm/next@15.5.27",
            "pkg:npm/react@19.3.0",
            "pkg:npm/pg@8.23.1",
            "pkg:npm/typescript@5.9.3",
        ):
            self.assertIn(expected, purls)

    def test_requirements_pins_covered(self) -> None:
        names = set()
        for line in REQUIREMENTS_PATH.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#"):
                names.add(line.split("==")[0])
        pypi = {c["purl"] for c in self.bom["components"] if c["purl"].startswith("pkg:pypi/")}
        for name in names:
            with self.subTest(package=name):
                self.assertTrue(any(p.startswith(f"pkg:pypi/{name}@") for p in pypi))


if __name__ == "__main__":
    unittest.main()
